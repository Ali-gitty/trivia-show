let changed = 0;
for (const item of bank) {
  const fix = fixes[item.id];
  if (!fix) continue;
  item.answer = fix.answer;
  item.options = [...fix.options];
  if (fix.question) item.question = fix.question;
  if (fix.hint) item.hint = fix.hint;
  if (!item.options.includes(item.answer)) {
    throw new Error(`answer missing from options for ${item.id}`);
  }
  changed += 1;
}

const softPattern = /أكثر من|أقل من|حوالي|نحو \d|قرابة|ما يزيد عن|على الأقل/;
const stillSoft = bank.filter(
  (item) => softPattern.test(item.answer) || item.options.some((option) => softPattern.test(option)),
);
if (stillSoft.length) {
  console.error(
    "still soft",
    stillSoft.map((item) => ({ id: item.id, answer: item.answer, options: item.options })),
  );
  process.exit(1);
}

writeFileSync(path, `${JSON.stringify(bank, null, 2)}\n`);
console.log("repaired", changed);
